#!/usr/bin/env python3
import os
import re
import json

base_dir = os.path.dirname(os.path.abspath(__file__))
fonts_dir = os.path.join(base_dir, "fonts")
fonts = []

for item in sorted(os.listdir(fonts_dir)):
    item_path = os.path.join(fonts_dir, item)
    if not os.path.isdir(item_path):
        continue

    css_dir = os.path.join(item_path, "css")
    fonts_sub_dir = os.path.join(item_path, "fonts")

    css_files = [f for f in os.listdir(css_dir) if f.endswith(".css")] if os.path.exists(css_dir) else []
    if not css_files:
        continue
    min_css = next((f for f in css_files if f.endswith(".min.css")), css_files[0])

    font_family = item
    css_path = os.path.join(css_dir, min_css)
    with open(css_path, "r", encoding="utf-8", errors="ignore") as f:
        content = f.read()
        m = re.search(r"font-family\s*:\s*[\x27\x22]([^\x27\x22]+)[\x27\x22]", content)
        if m:
            font_family = m.group(1).strip()
        else:
            m2 = re.search(r"font-family\s*:\s*([^;\}]+)", content)
            if m2:
                font_family = m2.group(1).strip().strip("'\"")

    font_files = os.listdir(fonts_sub_dir) if os.path.exists(fonts_sub_dir) else []
    formats = sorted(list(set([f.split(".")[-1].lower() for f in font_files if "." in f and f.split(".")[-1].lower() in ["woff2", "woff", "ttf", "eot", "svg"]])))

    upper = font_family.upper()
    
    # Collection / Brand
    if "BPG" in upper:
        category = "BPG"
    elif "ALK" in upper:
        category = "ALK"
    elif "ARIAL" in upper:
        category = "Arial GEO"
    elif "DEJAVU" in upper:
        category = "DejaVu"
    elif "MG" in upper:
        category = "MG"
    elif "ARCHY" in upper:
        category = "Archy"
    else:
        category = "Classic"

    # Script type
    if "CAPS" in upper or "MTAVRULI" in upper or "MTAV" in upper:
        script_type = "Mtavruli"
    else:
        script_type = "Mkhedruli"

    # Weight / Style
    if "BOLDITALIC" in upper or ("BOLD" in upper and "ITALIC" in upper):
        weight = "Bold Italic"
    elif "BOLD" in upper:
        weight = "Bold"
    elif "ITALIC" in upper or "OBLIQUE" in upper:
        weight = "Italic"
    elif "LIGHT" in upper or "THIN" in upper:
        weight = "Light"
    elif "COND" in upper:
        weight = "Condensed"
    else:
        weight = "Regular"

    fonts.append({
        "name": font_family,
        "slug": item,
        "cssFile": min_css,
        "category": category,
        "scriptType": script_type,
        "weight": weight,
        "formats": formats
    })

# Write fonts.json
json_path = os.path.join(base_dir, "fonts.json")
with open(json_path, "w", encoding="utf-8") as f:
    json.dump(fonts, f, indent=2, ensure_ascii=False)

# Write fonts-data.js so index.html works with zero network delay or file:// protocol
js_data_dir = os.path.join(base_dir, "assets", "js")
os.makedirs(js_data_dir, exist_ok=True)
js_path = os.path.join(js_data_dir, "fonts-data.js")
with open(js_path, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by build-catalog.py - do not edit manually\n")
    f.write("window.GEORGIAN_FONTS = " + json.dumps(fonts, indent=2, ensure_ascii=False) + ";\n")

print(f"Successfully cataloged {len(fonts)} fonts into fonts.json and assets/js/fonts-data.js!")
